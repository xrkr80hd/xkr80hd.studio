-- YourLocal community: self-serve member accounts and private uploads.
-- Safe to run more than once. Touches no existing table.

create table if not exists public.community_members (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  handle text not null unique check (handle ~ '^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$'),
  display_name text not null check (char_length(display_name) between 2 and 80),
  member_type text not null check (member_type in ('business', 'artist', 'band', 'podcast', 'blogger')),
  city text check (char_length(city) <= 80),
  state text check (state ~ '^[A-Z]{2}$'),
  zip text check (zip ~ '^[0-9]{5}$'),
  tagline text check (char_length(tagline) <= 140),
  bio text check (char_length(bio) <= 2000),
  website_url text check (char_length(website_url) <= 300),
  avatar_path text,
  cover_path text,
  status text not null default 'active' check (status in ('active', 'hidden', 'banned')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_community_members_type on public.community_members(member_type, status);
create index if not exists idx_community_members_zip on public.community_members(zip);
create index if not exists idx_community_members_state_city on public.community_members(state, city);

create table if not exists public.community_media (
  id bigint generated by default as identity primary key,
  member_id uuid not null references public.community_members(id) on delete cascade,
  kind text not null check (kind in ('audio', 'video', 'image')),
  title text check (char_length(title) <= 120),
  storage_path text not null unique,
  mime_type text not null,
  size_bytes bigint not null check (size_bytes > 0),
  created_at timestamptz not null default now()
);

create index if not exists idx_community_media_member on public.community_media(member_id, kind, created_at desc);

-- Hard cap per member, even if two uploads finish at the same moment:
-- 3 audio, 2 video, 12 images.
create or replace function public.community_media_enforce_limit()
returns trigger
language plpgsql
as $$
declare
  existing integer;
  allowed integer;
begin
  perform pg_advisory_xact_lock(hashtext(new.member_id::text || ':' || new.kind));
  select count(*) into existing from public.community_media where member_id = new.member_id and kind = new.kind;
  allowed := case new.kind when 'audio' then 3 when 'video' then 2 else 12 end;
  if existing >= allowed then
    raise exception 'community_media limit reached for %', new.kind;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_community_media_limit on public.community_media;
create trigger trg_community_media_limit
before insert on public.community_media
for each row execute function public.community_media_enforce_limit();

drop trigger if exists trg_community_members_updated_at on public.community_members;
create trigger trg_community_members_updated_at
before update on public.community_members
for each row execute function public.set_updated_at();

-- Only the website's server (service role) reads or writes these tables.
alter table public.community_members enable row level security;
alter table public.community_media enable row level security;
revoke all on public.community_members from anon, authenticated;
revoke all on public.community_media from anon, authenticated;
grant select, insert, update, delete on public.community_members to service_role;
grant select, insert, update, delete on public.community_media to service_role;
grant usage, select on sequence public.community_media_id_seq to service_role;

